def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    count = 0
    by_rarity = {}
    for item in ITEMS:
        write_item(item)
        count += 1
        r = item.get("rarity", "?")
        by_rarity[r] = by_rarity.get(r, 0) + 1

    print(f"Generated {count} items in {OUT_DIR}")
    for r in ["Común", "Poco Común", "Rara", "Muy Rara", "Legendaria"]:
        print(f"  {r}: {by_rarity.get(r, 0)}")

if __name__ == "__main__":
    main()

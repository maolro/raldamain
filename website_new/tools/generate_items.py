"""
Raldamain Item Generator
========================
Generates 100+ item JSON files in data/equipment/
Run: python tools/generate_items.py
"""
import os, json

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(os.path.dirname(SCRIPT_DIR), "data", "equipment")

def write_item(item):
    path = os.path.join(OUT_DIR, f"{item['id']}.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(item, f, indent=2, ensure_ascii=False)

def weapon(id, name, subtype, rarity, damage, dmgType, price, desc, range_="Cuerpo a cuerpo", props=None, abilities=None, lore=None, type_="Arma"):
    item = {"id": id, "name": name, "type": type_, "subtype": subtype, "rarity": rarity,
            "image": f"{id}.jpg", "description": desc, "damage": damage, "damageType": dmgType,
            "price": price, "range": range_}
    if props: item["properties"] = props
    if abilities: item["abilities"] = abilities
    if lore: item["lore"] = lore
    return item

def armor(id, name, subtype, rarity, defense, price, desc, props=None, abilities=None, penalties=None, lore=None, type_="Armadura"):
    item = {"id": id, "name": name, "type": type_, "subtype": subtype, "rarity": rarity,
            "image": f"{id}.jpg", "description": desc, "defense": str(defense), "price": price}
    if props: item["properties"] = props
    if abilities: item["abilities"] = abilities
    if penalties: item["penalties"] = penalties
    if lore: item["lore"] = lore
    return item

def magic_item(id, name, subtype, rarity, price, desc, props=None, abilities=None, lore=None):
    item = {"id": id, "name": name, "type": "Objeto Mágico", "subtype": subtype, "rarity": rarity,
            "image": f"{id}.jpg", "description": desc, "price": price}
    if props: item["properties"] = props
    if abilities: item["abilities"] = abilities
    if lore: item["lore"] = lore
    return item

def ab(name, cost, uses, desc):
    return {"name": name, "cost": cost, "uses": uses, "description": desc}

